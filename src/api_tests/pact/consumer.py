"""Consumer-side Pact setup, and the provenance every generated contract carries.

**These contracts are a Python model of the mobile clients' expectations.** They are authored here,
in pytest, from the backend's OpenAPI document and the Mobile Test Playground's documented flows. They
do *not* prove that the Android or iOS networking code emits the same requests: as of this writing
the Android app's Retrofit client (`core/data/.../remote/ShopApi.kt`) talks to an in-process
interceptor with a different, camelCase DTO shape and never calls this backend, and there is no iOS
client in the repository. Every pact file says so in its metadata, so the provenance survives the
trip through a Pact Broker.

Contracts generated by the real mobile apps can still be verified and published — drop them into
`MTP_PACT_EXTERNAL_DIR`.
"""

from __future__ import annotations

import json
from pathlib import Path

from pact import Pact

from api_tests import __version__
from api_tests.config import Settings

PROVENANCE_NAMESPACE = "mobileTestPlayground"
PROVENANCE: dict[str, str] = {
    "contractSource": "python-model",
    "authoredBy": f"mtp-api-tests {__version__}",
    "provenance": (
        "Python model of the mobile clients' API expectations, authored in pytest. Not generated by "
        "the Android or iOS networking client; does not prove either app sends these requests."
    ),
}


def new_pact(settings: Settings) -> Pact:
    return (
        Pact(settings.pact_consumer_name, settings.pact_provider_name)
        .with_specification("V4")
        .with_metadata(PROVENANCE_NAMESPACE, PROVENANCE)
    )


def pact_file(settings: Settings) -> Path:
    """Where pact-python writes this consumer/provider pair: `<consumer>-<provider>.json`."""
    return settings.pact_dir / f"{settings.pact_consumer_name}-{settings.pact_provider_name}.json"


def contract_source(path: Path) -> str:
    """`python-model` for our files; `external` for anything without our provenance marker."""
    try:
        metadata = json.loads(path.read_text(encoding="utf-8")).get("metadata", {})
    except (OSError, ValueError):
        return "unreadable"
    marker = metadata.get(PROVENANCE_NAMESPACE, {})
    return str(marker.get("contractSource", "external")) if isinstance(marker, dict) else "external"
